"""English versions of an Icelandic question set, same expected tables: English search measured the way
Icelandic search is (dev: 270 questions; before this, English had only the organizers' 30).

    LLM_BASE_URL=... LLM_MODEL=... python eval/build_english_set.py               # dev -> questions_dev_en.jsonl
    python eval/build_english_set.py eval/questions_test.jsonl eval/questions_test_en.jsonl   # frozen, report only

The model writes the question the way an English-speaking user would ask it; place names and years stay.
Generated by an LLM, so it is tuning data like dev itself, not a human test.
"""
import argparse
import json
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from hagstofa import llm  # noqa: E402
from hagstofa.retrieve import is_english  # noqa: E402

PROMPT = (
    "Translate this Icelandic question about Icelandic official statistics into natural English, the way an "
    "English-speaking user would type it into a statistics chatbot. Keep place names as they are written, and "
    "keep every year, number and age range. Reply with the English question only, nothing else."
)


def translate(question):
    text = llm.chat(PROMPT, question).strip().strip('"').strip()
    return text.splitlines()[0].strip() if text else ""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("source", nargs="?", default=str(ROOT / "eval/questions_dev.jsonl"))
    ap.add_argument("out", nargs="?", default=str(ROOT / "eval/questions_dev_en.jsonl"))
    ap.add_argument("--workers", type=int, default=16)
    args = ap.parse_args()
    rows = [json.loads(line) for line in open(args.source, encoding="utf-8")]
    rows = [r for r in rows if not is_english(r["q"])]
    with ThreadPoolExecutor(args.workers) as pool:
        english = list(pool.map(translate, (r["q"] for r in rows)))
    kept = 0
    with open(args.out, "w", encoding="utf-8") as f:
        for r, en in zip(rows, english):
            if not en or not is_english(en):  # an empty or still-Icelandic reply: left out, counted below
                continue
            f.write(json.dumps({**r, "q": en, "lang": "en", "q_is": r["q"]}, ensure_ascii=False) + "\n")
            kept += 1
    print(f"{kept} of {len(rows)} questions translated -> {args.out}")


if __name__ == "__main__":
    main()
